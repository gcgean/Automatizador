const {app,BrowserWindow}=require('electron');
const assert=require('node:assert/strict');
const {snapshot,interact,describeTarget,runInPage}=require('../electron/browser.cjs');
const fs=require('node:fs');
const path=require('node:path');
const os=require('node:os');
const profile=fs.mkdtempSync(path.join(os.tmpdir(),'nexo-actions-'));
app.setPath('userData',profile);app.setPath('sessionData',profile);
app.whenReady().then(async()=>{
  let win;
  try{
    win=new BrowserWindow({show:false,webPreferences:{sandbox:true,contextIsolation:true,nodeIntegration:false}});
    await win.loadURL('data:text/html;charset=utf-8,'+encodeURIComponent('<!doctype html><html><body><button onclick="document.body.dataset.clicks=Number(document.body.dataset.clicks||0)+1">Clique de teste</button><label>Nome<input></label><label>Senha<input type="password" value="fake-password"></label><button disabled>Indisponível</button></body></html>'));
    const contents=win.webContents;
    let state=await snapshot(contents);
    const click=state.elements.find(e=>e.label==='Clique de teste');
    await assert.rejects(describeTarget(contents,{id:click.id,token:'referencia-incorreta'}),e=>e.code==='STALE_REFERENCE' && e.recoverable && /referência da página expirou/.test(e.message) && !/Script failed/.test(e.message));
    assert.equal(await contents.executeJavaScript('document.body.dataset.clicks'),undefined);
    await interact(contents,'click',{id:String(click.id)});
    assert.equal(await contents.executeJavaScript('document.body.dataset.clicks'),'1');
    const name=state.elements.find(e=>e.label==='Nome');
    await interact(contents,'fill',{id:name.id,value:'Teste do navegador'});
    assert.equal(await contents.executeJavaScript('document.querySelector("input").value'),'Teste do navegador');
    const password=state.elements.find(e=>e.type==='password');
    assert.equal(password.value,'[oculto]');
    await assert.rejects(interact(contents,'fill',{id:password.id,value:'não deve preencher'}),e=>e.code==='PROTECTED_FIELD' && !e.recoverable);
    const disabled=state.elements.find(e=>e.label==='Indisponível');
    await assert.rejects(interact(contents,'click',{id:disabled.id}),e=>e.code==='ELEMENT_DISABLED');
    await contents.executeJavaScript('document.querySelector("button").replaceWith(document.querySelector("button").cloneNode(true))');
    await assert.rejects(interact(contents,'click',{id:click.id}),e=>e.code==='ELEMENT_CHANGED' && e.recoverable);
    state=await snapshot(contents);
    await interact(contents,'click',{id:state.elements.find(e=>e.label==='Clique de teste').id});
    assert.equal(await contents.executeJavaScript('document.body.dataset.clicks'),'2');
    await contents.executeJavaScript(`document.body.insertAdjacentHTML('beforeend','<ul><li role="tab" tabindex="0">Aba Mensagens</li><li id="chat-row" style="cursor:pointer"><span>Marina Alves</span><span>Olá, tenho uma dúvida</span></li><li id="chat-ana" role="button" tabindex="0">Ana Silva</li><li style="display:none;cursor:pointer">Contato oculto</li></ul>');document.getElementById('chat-row').addEventListener('click',()=>document.body.dataset.openChat='Marina');`);
    state=await snapshot(contents);
    assert.ok(state.elements.some(e=>e.label==='Aba Mensagens'));
    const row=state.elements.find(e=>e.tag==='li' && e.label.includes('Marina Alves'));
    assert.ok(row,'Linha com cursor pointer deve ser detectada');
    assert.ok(!state.elements.some(e=>e.label.includes('Contato oculto')));
    await interact(contents,'click',{id:row.id});assert.equal(await contents.executeJavaScript('document.body.dataset.openChat'),'Marina');
    state=await snapshot(contents,{query:'ana silva'});assert.ok(state.elements.length>0);assert.ok(state.elements.every(e=>/Ana Silva/.test(e.label)));
    state=await snapshot(contents,{query:'marina'});
    const stale=state.elements.find(e=>e.tag==='li');
    await contents.executeJavaScript(`document.getElementById('chat-row').firstChild.textContent='Outra pessoa'`);
    await assert.rejects(interact(contents,'click',{id:stale.id}),e=>e.code==='ELEMENT_CHANGED');
    await assert.rejects(runInPage({executeJavaScript:async()=>{throw new Error('Script failed to execute');}},''),e=>e.code==='EXECUTION_INTERRUPTED' && !e.recoverable);
    console.log('PASS: cliques e campos, referências inválidas, linhas de chat clicáveis, abas ARIA, busca por nome, conteúdo alterado e campos protegidos.');
    win.destroy();app.exit(0);
  }catch(error){console.error(error);if(win)win.destroy();app.exit(1);}
});
