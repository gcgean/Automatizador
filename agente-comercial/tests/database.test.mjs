import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import http from 'node:http';
import crypto from 'node:crypto';
import {Pool} from 'pg';
import {PgStore} from '../server/pg-store.js';
import {Store} from '../server/store.js';
import {migrateJson} from '../server/migrate-json.js';
import {PasswordAuth} from '../server/auth.js';
import {createApp} from '../server/index.js';
import {DurableInbox} from '../server/inbox.js';

const connectionString=process.env.TEST_DATABASE_URL;
test('PostgreSQL real: migração, concorrência, relatórios e autenticação', {skip:!connectionString}, async()=>{
 const url=new URL(connectionString);
 assert.equal(url.hostname,'127.0.0.1');assert.equal(url.port,'5548','Os testes só podem usar o container isolado na porta 5548.');
 const admin=new Pool({connectionString});
 const schema='qa_'+crypto.randomBytes(8).toString('hex');
 await admin.query('CREATE SCHEMA '+schema);
 url.searchParams.set('options','-c search_path='+schema);
 const dir=await fs.mkdtemp(path.join(os.tmpdir(),'pg-migration-'));
 const store=new PgStore(url.toString(),dir);
 let server;
 try{
  await store.init({workerLock:true});
  const file=new Store(dir);await file.init();
  const phone='5511999990000';
  await file.updateLead(phone,{nome:'Teste QA',temperatura:'quente',optedOut:true,status:'bloqueado'});
  await file.saveConversation({phone,histories:{deepseek:[{role:'user',content:'Teste'}]},processedIds:['in1']});
  await file.recordEvent({id:'in1',phone,direction:'in',text:'=TESTE CSV'});
  await file.recordEvent({id:'out1',phone,direction:'out',text:'Resposta',state:'accepted',messageId:'meta1'});
  await file.recordDelivery({id:'meta1',status:'read'});
  await file.saveSettings({context:'Contexto migrado',aiProvider:'deepseek'});
  await file.saveInbox({job1:{message:{id:'in1',from:phone,text:'Teste'},status:'done',receivedAt:new Date().toISOString()}});
  const migrated=await migrateJson(store,dir);
  assert.deepEqual(migrated,{leads:1,conversations:1,messages:2,deliveries:1,jobs:1});
  assert.deepEqual(await migrateJson(store,dir),{alreadyImported:true});
  assert.equal((await store.listLeads())[phone].optedOut,true);
  assert.deepEqual((await store.getConversation(phone)).processedIds,['in1']);
  await Promise.all([store.updateLead(phone,{empresa:'Loja'}),store.updateLead(phone,{segmento:'Varejo'}),store.saveSettings({context:'Novo contexto'}),store.saveSettings({aiProvider:'openai'})]);
  assert.equal((await store.listLeads())[phone].empresa,'Loja');assert.equal((await store.listLeads())[phone].segmento,'Varejo');
  assert.equal((await store.getSettings()).context,'Novo contexto');assert.equal((await store.getSettings()).aiProvider,'openai');
  await store.recordDelivery({id:'meta1',status:'sent'});
  assert.equal((await store.getEvents(phone))[1].delivery.status,'read');
  const inbox=new DurableInbox({store,agent:{enqueue:async()=>{throw new Error('Não deve reprocessar trabalho concluído.');}}});await inbox.init();inbox.resume();await inbox.drain();assert.equal(inbox.jobs.job1.status,'done');
  const other=new PgStore(url.toString(),dir);try{await assert.rejects(other.init({workerLock:true}),/Já existe/);}finally{await other.close();}
  const report=await store.reports('2020-01-01','2030-01-01');assert.equal(report.messages.received,1);assert.equal(report.messages.read,1);assert.equal(report.leads.total,1);
  const config={adminEmail:'qa@example.com',adminSetupToken:'activation-test-only',publicUrl:'http://127.0.0.1',databaseUrl:url.toString(),panelToken:'legacy-token-must-not-work',aiProvider:'deepseek'};
  const auth=new PasswordAuth(store,config);await auth.init();
  server=http.createServer(createApp({config,store,inbox,auth,log:{error(){}}}));await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
  const root='http://127.0.0.1:'+server.address().port;
  const post=(route,body,cookie,origin)=>fetch(root+route,{method:'POST',headers:{'Content-Type':'application/json','X-Requested-With':'CommandPanel',...(cookie?{Cookie:cookie}:{}),...(origin?{Origin:origin}:{})},body:JSON.stringify(body)});
  assert.equal((await fetch(root+'/leads',{headers:{Authorization:'Bearer legacy-token-must-not-work'}})).status,401);
  assert.equal((await post('/auth/setup',{email:'qa@example.com',password:'Password-test-2026',setupToken:'wrong'})).status,401);
  assert.equal((await post('/auth/setup',{email:'qa@example.com',password:'Password-test-2026',setupToken:'activation-test-only'},null,'https://attacker.example')).status,403);
  const activated=await post('/auth/setup',{email:'qa@example.com',password:'Password-test-2026',setupToken:'activation-test-only'});assert.equal(activated.status,200);
  const cookie=activated.headers.get('set-cookie').split(';')[0];assert.match(activated.headers.get('set-cookie'),/HttpOnly/);assert.match(activated.headers.get('set-cookie'),/SameSite=Strict/);
  assert.equal((await post('/auth/setup',{email:'qa@example.com',password:'Password-test-2026',setupToken:'activation-test-only'})).status,401);
  assert.equal((await fetch(root+'/auth/me',{headers:{Cookie:cookie}})).status,200);
  assert.equal((await fetch(root+'/leads',{headers:{Cookie:cookie}})).status,200);
  const reportHTTP=await fetch(root+'/reports?from=2026-01-01&to=2026-12-31',{headers:{Cookie:cookie}});assert.equal(reportHTTP.status,200);assert.equal((await reportHTTP.json()).messages.read,1);
  assert.equal((await fetch(root+'/reports?from=2026-02-30',{headers:{Cookie:cookie}})).status,400);
  const csv=await fetch(root+'/reports/messages.csv?from=2026-01-01&to=2026-12-31',{headers:{Cookie:cookie}});assert.equal(csv.status,200);assert.match(await csv.text(),/'=TESTE CSV/);
  assert.equal((await post('/context',{text:'Ataque'},cookie,'https://attacker.example')).status,403);
  const changed=await post('/auth/password',{currentPassword:'Password-test-2026',newPassword:'Changed-password-2026'},cookie);assert.equal(changed.status,200);
  assert.equal((await fetch(root+'/auth/me',{headers:{Cookie:cookie}})).status,401);
  assert.equal((await post('/auth/login',{email:'qa@example.com',password:'Password-test-2026'})).status,401);
  const logged=await post('/auth/login',{email:'qa@example.com',password:'Changed-password-2026'});assert.equal(logged.status,200);
  const newCookie=logged.headers.get('set-cookie').split(';')[0];
  const persisted=await store.pool.query('SELECT password_hash,setup_hash FROM users');assert.match(persisted.rows[0].password_hash,/^scrypt\$/);assert.equal(persisted.rows[0].setup_hash,null);
  const sessionRows=await store.pool.query('SELECT token_hash FROM sessions');assert.ok(!sessionRows.rows.some(row=>newCookie.includes(row.token_hash)));
  await post('/auth/logout',{},newCookie);
  assert.equal((await fetch(root+'/auth/me',{headers:{Cookie:newCookie}})).status,401);
  for(let i=0;i<10;i++)await post('/auth/login',{email:'locked@example.com',password:'incorrect'});
  assert.equal((await post('/auth/login',{email:'locked@example.com',password:'incorrect'})).status,429);
 }finally{
  if(server)await new Promise(resolve=>server.close(resolve));
  await store.close();await admin.query('DROP SCHEMA '+schema+' CASCADE');await admin.end();await fs.rm(dir,{recursive:true,force:true});
 }
});
